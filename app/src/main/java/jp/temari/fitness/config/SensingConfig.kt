package jp.temari.fitness.config

/**
 * 本物の計測（センサーの読み取りと「歩いた／家のこと」の判別）の定数。
 *
 * しきい値は **すべて仮の値**。研究で使われる ENMO のしきい値は、研究用の機器を手首や腰に付けたときのもので、
 * スマホをポケットやかばんに入れたときの値ではない。実機でスタッフ・開発用画面の「今の揺れ」を見ながら決め直す。
 */
object SensingConfig {
    /** 判別の1区切りの長さ（秒）。この長さごとに「歩いた／家のこと／動いていない」を決める。 */
    const val EPOCH_SECONDS = 10

    /** 加速度を読む間隔（マイクロ秒）。50,000 = 1秒に 20 回。多すぎると電池を使い、少なすぎると揺れを取りこぼす。 */
    const val SAMPLING_PERIOD_US = 50_000

    /** センサーの値をまとめて受け取ってよい最大の遅れ（マイクロ秒）。まとめて受け取ると電池の節約になる。 */
    const val MAX_REPORT_LATENCY_US = 1_000_000

    /** 1区切り（10秒）にこの歩数以上あれば「歩いた」区切りとする。（仮） */
    const val WALK_MIN_STEPS_PER_EPOCH = 4

    /**
     * 歩いていない区切りで、揺れ（ENMO、単位 mg = 重力の1000分の1）の平均がこれ以上なら「家のこと」とする。（仮）
     * 研究では高齢者の手首で 10〜50mg 前後の値が使われている。スマホはポケットの中で揺れが小さくなりやすいので低めにしている。
     */
    const val LIFE_ENMO_THRESHOLD_MG = 25f

    /** 「家のこと」として動いた何秒で 1 ポイントにするか。（仮。20 秒なら 1 時間で 180 ポイント） */
    const val LIFE_SECONDS_PER_POINT = 20

    /** 歩数計センサーが無い端末で、加速度から1歩と数える揺れの大きさ（m/s²、重力を引いた値）。（仮） */
    const val STEP_DETECT_THRESHOLD_MS2 = 1.6f

    /** 加速度から歩数を数えるとき、1歩と次の1歩の最小の間隔（ミリ秒）。これより速い揺れは同じ1歩とみなす。 */
    const val STEP_MIN_INTERVAL_MS = 300L

    /** 加速度の大きさをなめらかにする割合（0〜1。小さいほどなめらか）。細かい振動を歩数に数えないため。 */
    const val STEP_SMOOTHING = 0.25f

    /** 記録をファイルに書き出す間隔（ミリ秒）。 */
    const val SAVE_INTERVAL_MILLIS = 60_000L

    /** 端末に残しておく日数。これより古い日は消す。 */
    const val KEEP_DAYS = 120L

    /** 標準の重力の大きさ（m/s²）。 */
    const val GRAVITY = 9.80665f
}
